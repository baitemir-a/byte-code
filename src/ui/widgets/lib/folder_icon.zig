/// Width and height of an icon, in UI units (the pack draws on 16x16).
pub const size: f32 = 16;

/// What a folder shows in front of its name (Settings): the same plain
/// folder for every one of them, the icon for its name, or nothing.
pub const Mode = enum { same, by_name, none };
pub var mode: Mode = .by_name;

/// Whether folders draw an icon at all.
pub fn shown() bool {
    return mode != .none;
}

