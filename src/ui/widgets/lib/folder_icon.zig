//! Folder icons from the folder pack (assets/folder-icons): picked by the
//! folder's name (src, tests, .github, ...), else the plain folder. Each
//! one comes in two shapes — open and shut — and the row fades from one to
//! the other as the folder opens. Like the file icons (file_icon.zig) they
//! are SVGs, rasterized with nanosvg the first time they are drawn, for
//! the display's density and the zoom.
