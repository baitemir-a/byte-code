fn iconFor(name: []const u8) Icon {
    if (mode != .by_name) return .folder;
    var buf: [64]u8 = undefined;
    if (name.len > buf.len) return .folder;
    const n = std.ascii.lowerString(buf[0..name.len], name);
    if (by_name.get(n)) |icon| return icon;
    if (by_alias.get(n)) |icon| return icon;
    // A leading dot is how a folder hides, not part of its name.
    if (n.len > 1 and n[0] == '.') {
        if (by_name.get(n[1..])) |icon| return icon;
        if (by_alias.get(n[1..])) |icon| return icon;
    }
    return .folder;
}

/// Rasterized icons, made on first use and remade when the pixel size
/// changes. Open and shut are kept apart.
const Rendered = struct { texture: rl.Texture2D, px: i32 };
var rendered: [svgs.len][2]?Rendered = @splat(.{ null, null });

extern fn svgRasterize(data: [*]const u8, len: usize, px: c_int) ?[*]u8;
extern fn svgFree(pixels: [*]u8) void;

fn texture(icon: Icon, open: bool, px: i32) ?rl.Texture2D {
    const slot = &rendered[@intFromEnum(icon)][@intFromBool(open)];
    if (slot.*) |r| {
        if (r.px == px) return r.texture;
        rl.unloadTexture(r.texture);
        slot.* = null;
    }
    const svg = if (open) svgs[@intFromEnum(icon)].open else svgs[@intFromEnum(icon)].shut;
    const pixels = svgRasterize(svg.ptr, svg.len, px) orelse return null;
    defer svgFree(pixels);
    const image: rl.Image = .{ .data = pixels, .width = px, .height = px, .mipmaps = 1, .format = .uncompressed_r8g8b8a8 };
    const t = rl.loadTextureFromImage(image) catch return null;
    rl.setTextureFilter(t, .bilinear);
    slot.* = .{ .texture = t, .px = px };
    return t;
}

/// Draws the icon for the folder `name` centered at `center`. `open` is
/// how far it has opened: the shut and open shapes cross over between 0
/// and 1, so an opening folder doesn't snap from one to the other.
pub fn draw(name: []const u8, open: f32, center: rl.Vector2) void {
    if (mode == .none) return;
    const t = std.math.clamp(open, 0, 1);
    const icon = iconFor(name);
    if (t < 1) drawOne(icon, false, center, 1 - t);
    if (t > 0) drawOne(icon, true, center, t);
}

fn drawOne(icon: Icon, open: bool, center: rl.Vector2, alpha: f32) void {
    // Screen pixels per UI unit: display density times zoom.
    const scale = @max(1, rl.getWindowScaleDPI().x) * theme.zoom;
    const px: i32 = @intFromFloat(@round(size * scale));
    const t = texture(icon, open, px) orelse return;
    const pixel = 1 / scale;
    const dest: rl.Rectangle = .{
        .x = @round((center.x - size / 2) / pixel) * pixel,
        .y = @round((center.y - size / 2) / pixel) * pixel,
        .width = size,
        .height = size,
    };
    const side: f32 = @floatFromInt(px);
    const tint: rl.Color = .{ .r = 255, .g = 255, .b = 255, .a = @intFromFloat(@round(std.math.clamp(alpha, 0, 1) * 255)) };
    rl.drawTexturePro(t, .{ .x = 0, .y = 0, .width = side, .height = side }, dest, .{ .x = 0, .y = 0 }, 0, tint);
}

/// Frees the rasterized icons (before the window closes).
pub fn unload() void {
    for (&rendered) |*pair| for (pair) |*slot| if (slot.*) |r| {
        rl.unloadTexture(r.texture);
        slot.* = null;
    };
}
